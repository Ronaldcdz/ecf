/**
 * Checks the theme in `main.css` and `app.config.ts` against the design decisions
 * (ADR 0018-0032) and WCAG 2 level AA. See `docs/sistema-de-diseno.md`.
 */
import { beforeAll, describe, expect, it, vi } from 'vitest'
import mainCss from '../assets/css/main.css?raw'
import tailwindTheme from 'tailwindcss/theme.css?raw'
import { contrastRatio, hexToOklch, oklchToHex } from './color'
import { BRAND_PALETTES, STEPS, type Step } from './palette'

type Scale = Record<Step, string>

/** Reads `--color-<name>-<step>: #hex;` declarations from main.css. */
function brandScale(name: string): Partial<Scale> {
  const scale: Partial<Scale> = {}
  for (const [, step, hex] of mainCss.matchAll(
    new RegExp(`--color-${name}-(\\d+):\\s*(#[0-9a-f]{6})`, 'g'),
  )) {
    scale[Number(step) as Step] = hex
  }
  return scale
}

/** Reads a standard Tailwind color (declared in OKLCH) as hex. */
function tailwind(name: string, step: Step): string {
  const match = tailwindTheme.match(
    new RegExp(
      `--color-${name}-${step}:\\s*oklch\\(([\\d.]+)% ([\\d.]+) ([\\d.]+)\\)`,
    ),
  )
  if (!match) throw new Error(`Tailwind color ${name}-${step} not found`)
  const [, l, c, h] = match.map(Number)
  return oklchToHex({ l: l! / 100, c: c!, h: h! })
}

/** Returns the body of a CSS block such as `:root { ... }`. */
function cssBlock(selector: string): string {
  const escaped = selector.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
  return mainCss.match(new RegExp(`${escaped}\\s*\\{([^}]*)\\}`))?.[1] ?? ''
}

const blue = brandScale('brand-blue') as Scale
const purple = brandScale('brand-purple') as Scale
const gray = brandScale('brand-gray') as Scale
const WHITE = '#ffffff'

describe('brand palettes in main.css', () => {
  it.each(['brand-blue', 'brand-purple', 'brand-gray'])(
    '%s has the 11 steps 50-950',
    (name) => {
      expect(Object.keys(brandScale(name)).map(Number)).toEqual([...STEPS])
    },
  )

  it('places each brand hex on the step that matches its lightness (ADR 0018)', () => {
    expect(blue[600]).toBe('#247ba0')
    expect(purple[950]).toBe('#2f0147')
    expect(gray[100]).toBe('#f1f2ee')
    expect(gray[500]).toBe('#717c89')
    expect(gray[900]).toBe('#1c1c1c')
  })

  it('matches the scales generated by palette.ts, so the CSS cannot drift from the method', () => {
    expect(blue).toEqual(BRAND_PALETTES['brand-blue'])
    expect(purple).toEqual(BRAND_PALETTES['brand-purple'])
    expect(gray).toEqual(BRAND_PALETTES['brand-gray'])
  })

  it.each([
    ['brand-blue', blue],
    ['brand-purple', purple],
    ['brand-gray', gray],
  ])('%s gets darker at every step', (_name, scale) => {
    const lightness = STEPS.map((step) => hexToOklch(scale[step]).l)
    const sorted = [...lightness].sort((a, b) => b - a)
    expect(lightness).toEqual(sorted)
  })
})

describe('Nuxt UI configuration', () => {
  let colors: Record<string, string>

  beforeAll(async () => {
    vi.stubGlobal('defineAppConfig', (config: unknown) => config)
    const { default: appConfig } = (await import('../app.config')) as {
      default: { ui: { colors: Record<string, string> } }
    }
    colors = appConfig.ui.colors
  })

  it('maps the semantic colors to the brand and standard palettes (ADR 0018, 0028)', () => {
    expect(colors).toEqual({
      primary: 'brand-blue',
      secondary: 'brand-purple',
      neutral: 'brand-gray',
      success: 'green',
      warning: 'yellow',
      info: 'blue',
      error: 'red',
    })
  })

  it('overrides the light-mode shades decided in ADR 0025, 0026, 0027 and 0032', () => {
    const root = cssBlock(':root')
    expect(root).toContain('--ui-primary: var(--ui-color-primary-600)')
    expect(root).toContain('--ui-secondary: var(--ui-color-secondary-950)')
    expect(root).toContain('--ui-text-muted: var(--ui-color-neutral-600)')
    for (const status of ['success', 'warning', 'info', 'error']) {
      expect(root).toContain(`--ui-${status}: var(--ui-color-${status}-700)`)
    }
  })

  it('gives text-dimmed (placeholders) the same shade as text-muted (ADR 0033)', () => {
    expect(cssBlock(':root')).toContain(
      '--ui-text-dimmed: var(--ui-color-neutral-600)',
    )
    expect(cssBlock('.dark')).toContain(
      '--ui-text-dimmed: var(--ui-color-neutral-400)',
    )
  })

  it('uses a 0.5rem radius (ADR 0020)', () => {
    expect(cssBlock(':root')).toContain('--ui-radius: 0.5rem')
  })

  it('uses Work Sans as the sans-serif font (ADR 0019)', () => {
    expect(cssBlock('@theme static')).toMatch(/--font-sans:\s*'Work Sans'/)
  })
})

